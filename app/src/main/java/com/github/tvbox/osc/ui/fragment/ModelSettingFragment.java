    private void restartAppAfterConfigChanged() {
        Toast.makeText(mContext, "配置已切换,即将自动重启应用!", Toast.LENGTH_SHORT).show();
        new Handler().postDelayed(new Runnable() {
            @Override
            public void run() {
                restartApp();
            }
        }, 3000);
    }

    private void restartApp() {
        if (mContext == null) return;
        Intent intent = mContext.getPackageManager().getLaunchIntentForPackage(mContext.getPackageName());
        if (intent != null) {
            intent.addFlags(Intent.FLAG_ACTIVITY_CLEAR_TOP);
            startActivity(intent);
            System.exit(0);
        }
    }

    private void onClickAudioPassthrough(View v) {
        FastClickCheckUtil.check(v);
        Hawk.put(HawkConfig.PLAYER_AUDIO_PASSTHROUGH, !Hawk.get(HawkConfig.PLAYER_AUDIO_PASSTHROUGH, false));
        AudioPassthroughVolumePolicy.enforceMaximum(getContext());
        tvAudioPassthrough.setText(Hawk.get(HawkConfig.PLAYER_AUDIO_PASSTHROUGH, false) ? "开启" : "关闭");
    }

    private void onClickClearCache(View v) {
        FastClickCheckUtil.check(v);
        String cachePath = FileUtils.getCachePath();
        File cacheDir = new File(cachePath);
        String cspCachePath = FileUtils.getFilePath()+"/csp/";
        File cspCacheDir = new File(cspCachePath);
        if (!cacheDir.exists() && !cspCacheDir.exists()) return;
        new Thread(() -> {
            try {
                if(cacheDir.exists())FileUtils.cleanDirectory(cacheDir);
                if(cspCacheDir.exists()){
                    FileUtils.cleanDirectory(cspCacheDir);
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        }).start();
        Toast.makeText(getContext(), "播放&JAR缓存已清空", Toast.LENGTH_LONG).show();
    }


